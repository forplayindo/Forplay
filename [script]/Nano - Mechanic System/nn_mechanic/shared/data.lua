-- Custom engines from Config.EngineSwap: maps fake modIndex (100+) to engine config key
Data.CustomEngineStartIndex = 100
Data.CustomEngines = {}
Data.CustomEngineKeyToModIndex = {}

if Config and Config.EngineSwap and Config.EngineSwap.engines then
    local keys = {}
    for k in pairs(Config.EngineSwap.engines) do
        keys[#keys + 1] = k
    end
    table.sort(keys)
    for i, key in ipairs(keys) do
        local modIndex = Data.CustomEngineStartIndex + (i - 1)
        Data.CustomEngines[modIndex] = key
        Data.CustomEngineKeyToModIndex[key] = modIndex
    end
end