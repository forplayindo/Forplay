if Config.Framework ~= 'qb' and Config.Framework ~= 'qbx' then return end
local isQbox = Config.Framework == 'qbx'
if not isQbox then QBCore = exports[Config.CustomStringQBExport or 'qb-core']:GetCoreObject() end
local function readData()
    local data
    if isQbox then data = exports.qbx_core:GetPlayerData() else data = QBCore.Functions.GetPlayerData() end
    return type(data) == 'table' and data or {}
end
local function isReady() return PlayerLoaded() end
PlayerData = readData()

function MenuClose()
    if QBCore and QBCore.UI and QBCore.UI.Menu then QBCore.UI.Menu.CloseAll() end
    lib.hideContext()
end

CreateThread(function()
    Wait(1000)
    if isReady() then LoadPetCharacter(readData, isReady) end
end)
RegisterNetEvent('QBCore:Client:OnPlayerLoaded', function() LoadPetCharacter(readData, isReady) end)
RegisterNetEvent('QBCore:Client:OnPlayerUnload', UnloadPetCharacter)
RegisterNetEvent('QBCore:Player:SetPlayerData', SetPetPlayerData)
RegisterNetEvent('QBCore:Client:OnJobUpdate', SetPetPlayerJob)

function GetJobName() return (GetFrameworkPlayerData().job or {}).name end
function GetIdentifier() return GetFrameworkPlayerData().citizenid end
function GetInventory() return GetFrameworkPlayerData().items or {} end
