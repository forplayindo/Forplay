exports('usePetHouse', function(data, slot)
    if Config.Inventory ~= 'ox_inventory' or not Config.EnablePetHouse or type(data) ~= 'table' then return end
    local kind
    for name, definition in pairs(Config.PetHouseModels) do
        if definition.itemName == data.name then kind = name; break end
    end
    if not kind then return end
    exports.ox_inventory:useItem(data, function(used)
        if used then TriggerEvent('electus_pets:placeProp', kind) end
    end)
end)
