CREATE TABLE IF NOT EXISTS electus_pets (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  owner VARCHAR(80) NOT NULL,
  name VARCHAR(64) NOT NULL,
  data LONGTEXT NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY owner_pet (owner, name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS electus_pet_houses (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  owner VARCHAR(80) NOT NULL,
  house_type VARCHAR(64) NOT NULL,
  coords LONGTEXT NOT NULL,
  pets LONGTEXT NOT NULL,
  PRIMARY KEY (id),
  KEY owner_houses (owner)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS electus_pet_friends (
  owner VARCHAR(80) NOT NULL,
  friends LONGTEXT NOT NULL,
  PRIMARY KEY (owner)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
