function GetAccessoryLabel(item) return GetItemLabel(item) end

function IsAccessoryCompatible(model, item)
    return Config.AddonAccessories[model] ~= nil and Config.AddonAccessories[model][item] ~= nil
end

function PetAccessoryBone(entity, bone)
    if type(bone) == 'string' then return GetEntityBoneIndexByName(entity, bone) end
    return GetPedBoneIndex(entity, bone)
end

function AttachPetAccessory(prop, entity, bone, fit)
    if bone == nil or bone < 0 then return false end
    local offset, rot = fit.offset, fit.rot
    AttachEntityToEntity(prop, entity, bone, offset.x, offset.y, offset.z,
        rot.x, rot.y, rot.z, false, false, false, fit.pedRotation, fit.rotationOrder, true)
    return true
end

function UpdateAccessories(index)
    local pet = CurrentPets[index]
    if not pet then return end
    pet.hasBag = pet.accessories and pet.accessories.bag ~= nil
    -- The server's public record drives cosmetics on every client, including the owner.
    -- Before spawn confirmation there is no public record; the first sync renders it.
    if SyncPetVisuals then SyncPetVisuals() end
end

exports('isAccessoryCompatible', IsAccessoryCompatible)
exports('updateAccessories', UpdateAccessories)
