-- Resolve once on each side before any framework adapter is loaded.
local aliases = { qbox = 'qbx', qbx_core = 'qbx', qbcore = 'qb', ['qb-core'] = 'qb', es_extended = 'esx' }
local configured = Config.Framework or 'auto'
assert(type(configured) == 'string', 'electus_pets: Config.Framework must be a string')
configured = configured:lower():match('^%s*(.-)%s*$')
local selected = aliases[configured] or configured
if selected == 'auto' then
    if GetResourceState('qbx_core') == 'started' then
        selected = 'qbx'
    elseif GetResourceState(Config.CustomStringQBExport or 'qb-core') == 'started' then
        selected = 'qb'
    elseif GetResourceState('es_extended') == 'started' then
        selected = 'esx'
    end
end
assert(selected == 'esx' or selected == 'qb' or selected == 'qbx',
    'electus_pets: start es_extended, qb-core or qbx_core first, or set Config.Framework explicitly')
Config.Framework = selected
